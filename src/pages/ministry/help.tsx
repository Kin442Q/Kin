import { uiText } from '../../i18n/uiText'
import type { HelpMap } from '../../components/TableHelp'
import type { Metrics } from '../../api/ministryApi'

/* ============================================================
   Пояснения к таблицам кабинета министерства: что значит каждая колонка, как она считается
   и на чём основано значение в ячейке. Тексты совпадают с расчётом на сервере
   (server/src/modules/ministry/ministry.service.ts): меняя расчёт, правьте и их.
   ============================================================ */

type Row = Metrics & { students?: number; teachers?: number }

const n = (value: number) => value.toLocaleString('ru-RU')

const gradesBasis = (r: Row) =>
  r.gradesCount > 0 ? uiText('По {0} оценкам за период', n(r.gradesCount)) : uiText('Нет данных: за период не было оценок')

const attendanceBasis = (r: Row) =>
  r.attendanceMarks > 0
    ? uiText('По {0} отметкам посещаемости за период', n(r.attendanceMarks))
    : uiText('Нет данных: за период не было отметок посещаемости')

/** Колонки таблиц министерства: ключ — заголовок колонки по-русски. */
export function ministryHelp<T extends Row>(): HelpMap<T> {
  return {
    '#': {
      help: uiText('Место в рейтинге по среднему баллу среди школ этой выборки. Школы без оценок места не получают.'),
    },
    'Школа': { help: uiText('Название школы так, как её завёл владелец платформы.') },
    'Область': { help: uiText('Область, к которой школа привязана в справочнике регионов.') },
    'Район или город': {
      help: uiText('Район или город, к которому школа привязана в справочнике регионов. «Не указан» — школе ещё не назначен район.'),
    },
    'Школ': { help: uiText('Сколько действующих школ входит в эту строку. Демонстрационные школы не считаются.') },
    'Учеников': {
      help: uiText('Ученики со статусом «учится» на сегодняшний день: архивные и временно не посещающие не входят.'),
    },
    'Учителей': {
      help: uiText('Действующие учителя, заведённые в системе. Если школа не внесла учителей, здесь будет 0 и нагрузку посчитать нельзя.'),
    },
    'Учеников на учителя': {
      help: uiText('Число учеников, делённое на число учителей. Чем выше, тем больше нагрузка на одного учителя. Если учителей в системе нет, стоит прочерк.'),
      basis: (r) =>
        r.students != null && r.teachers != null ? uiText('Учеников: {0}, учителей: {1}', n(r.students), n(r.teachers)) : null,
    },
    'Средний балл': {
      help: uiText('Средняя оценка за период в процентах от максимума шкалы школы (5 или 10 баллов): 100 % — все оценки наивысшие. Так школы с разными шкалами можно сравнивать. Считается по всем оценкам, поставленным за выбранный период.'),
      basis: gradesBasis,
    },
    'Качество знаний': {
      help: uiText('Доля оценок «хорошо» и «отлично» среди всех оценок за период: 4 и 5 по пятибалльной шкале, 7 и выше по десятибалльной.'),
      basis: gradesBasis,
    },
    'Успеваемость': {
      help: uiText('Доля оценок не ниже «удовлетворительно» среди всех оценок за период: 3 и выше по пятибалльной шкале, 4 и выше по десятибалльной.'),
      basis: gradesBasis,
    },
    'Посещаемость': {
      help: uiText('Доля отметок «присутствовал» среди всех отметок посещаемости за период. Каникулы и отпуска в расчёт не входят.'),
      basis: attendanceBasis,
    },
    'Болеют': {
      help: uiText('Доля отметок «болеет» среди всех отметок посещаемости за период (присутствовал, отсутствовал, болеет). Чем меньше, тем лучше.'),
      basis: attendanceBasis,
    },
    'Данные': {
      help: uiText('Заполнила ли школа оценки, посещаемость и учителей за период. «Неполные» значит, что чего-то нет: такая школа не попадает в средние показатели.'),
      cell: false,
    },
  }
}

