type DirectorTable = 'classes' | 'subjects' | 'support' | 'daily' | 'journals' | 'teachers'

const coverageBasis = (row: any) =>
  row?.coverage ? uiText('Пар «ученик — предмет» с отметкой: {0} из {1}', row.coverage.assessed, row.coverage.expected) : null

/** Колонки таблиц отчёта: ключ — заголовок колонки по-русски. */
export function directorHelp(table: DirectorTable): HelpMap<any> {
  const marks = {
    help: uiText('Сколько отметок поставлено в журнал за выбранный период. Это записи журнала, а не итоговые оценки.'),
  }
  const average = {
    help: uiText('Среднее арифметическое текущих отметок за период. Считается по выбранной шкале анализа; пока шкала не выбрана, средний балл не показывается.'),
    basis: (row: any) => (row?.count != null ? uiText('По {0} отметкам', row.count) : null),
  }
  const poor = {
    help: uiText('Отметки ниже порога положительной оценки из фильтров отчёта. Шкала и пороги задаются явно.'),
  }
  const coverage = {
    help: uiText('Доля пар «ученик — предмет» из текущего расписания, по которым за период есть хотя бы одна отметка. Это не заполненность журнала и не доказательство проведённых уроков.'),
    basis: coverageBasis,
  }

  switch (table) {
    case 'classes':
      return {
        'Учеников': { help: uiText('Сколько учеников сейчас числится в классе.') },
        'Текущих отметок': marks,
        'Средний балл': average,
        // в ячейке уже есть своя подсказка с числами, поэтому две подряд не нужны
        'Охват оцениванием': { ...coverage, cell: false },
        'Оценённых учеников': {
          help: uiText('Сколько учеников класса получили хотя бы одну отметку за период. Показывается, когда выбрана шкала анализа.'),
        },
        'Учеников с низкими отметками': {
          help: uiText('Сколько учеников имеют хотя бы одну низкую отметку. Ученик с несколькими низкими отметками учитывается один раз.'),
        },
        'Доля среди оценённых': {
          help: uiText('Ученики с низкими отметками, делённые на оценённых учеников класса, в процентах.'),
        },
      }
    case 'subjects':
      return {
        'Текущих отметок': marks,
        'Средний балл': {
          help: uiText('Среднее арифметическое контрольных и экзаменационных отметок по предмету за период.'),
        },
        'Низких текущих отметок': poor,
        'Оценок высокого уровня': {
          help: uiText('Количество отметок не ниже порога качества знаний из фильтров отчёта.'),
        },
      }
    case 'support':
      return {
        'Классный руководитель': { help: uiText('Классный руководитель класса, в котором учится ученик.') },
        'Помощь по предметам': {
          help: uiText('По каким предметам нужна помощь: средний балл по предмету и даты низких отметок.'),
        },
        'Низких текущих отметок': poor,
        'Предметы с низкими отметками': {
          help: uiText('Предметы, по которым у ученика есть низкие отметки за период.'),
        },
        'Нет оценок по предметам': {
          help: uiText('Предметы текущего расписания, по которым у ученика нет ни одной отметки за период.'),
        },
        'Дней отсутствия без уточнения': {
          help: uiText('Сколько дней ученик отмечен «отсутствует» без причины (не болезнь и не отпуск). От трёх дней — основание для внимания.'),
        },
        'Последняя оценка': { help: uiText('Дата последней отметки ученика за период.') },
      }
    case 'daily':
      return {
        'Присутствуют': { help: uiText('Сколько учеников отмечено «присутствует» в этот день.') },
        'Отсутствие без уточнения': { help: uiText('Сколько учеников отмечено «отсутствует» без указания причины.') },
        'Болеют': { help: uiText('Сколько учеников отмечено «болеет».') },
        'В отпуске': { help: uiText('Сколько учеников отмечено «отпуск» или «каникулы».') },
        'Записей': { help: uiText('Всего отметок посещаемости за день: от них считаются проценты.') },
      }
    case 'journals':
      return {
        'Пар с оценками': {
          help: uiText('Сколько пар «ученик — предмет» имеют хотя бы одну отметку за период.'),
        },
        'Пар по расписанию': {
          help: uiText('Сколько пар «ученик — предмет» должно быть по текущему расписанию: учеников класса, умноженных на предметы в расписании.'),
        },
        'Охват оцениванием': coverage,
      }
    case 'teachers':
      return {
        'Уроков в неделю': {
          help: uiText('Сколько уроков стоит у учителя в недельном расписании. Записи с неверным временем не считаются.'),
        },
        'Минут по расписанию': {
          help: uiText('Суммарная длительность этих уроков за неделю. Это плановая нагрузка, а не фактически проведённые часы.'),
        },
        'Классов': { help: uiText('В скольких разных классах у учителя есть уроки по расписанию.') },
        'Внесено оценок': { help: uiText('Сколько оценок внёс учитель за выбранный период.') },
        'Дней с внесением оценок': {
          help: uiText('В скольких разных днях выбранного периода учитель вносил оценки.'),
        },
        'Задано ДЗ': {
          help: uiText('Сколько домашних заданий создал учитель со сроком сдачи в выбранном периоде.'),
        },
      }
  }
}
